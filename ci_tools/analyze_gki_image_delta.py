#!/usr/bin/env python3
"""Read-only deep binary delta diagnostic for ARM64 kernel Images."""
import argparse
import bisect
import hashlib
import json
import pathlib
import re

p = argparse.ArgumentParser()
p.add_argument("--built", required=True, type=pathlib.Path)
p.add_argument("--google", required=True, type=pathlib.Path)
p.add_argument("--system-map", type=pathlib.Path)
p.add_argument("--output", required=True, type=pathlib.Path)
args = p.parse_args()
a, b = args.built.read_bytes(), args.google.read_bytes()
if len(a) != len(b) or len(a) < 10000:
    raise SystemExit("Unusable sizes: no offset-aligned comparison possible")
positions = [i for i,(x,y) in enumerate(zip(a,b)) if x != y]
runs = []
for i in positions:
    if runs and i == runs[-1]["end"]+1:
        runs[-1]["end"] = i
        runs[-1]["count"] += 1
    else:
        runs.append({"start":i,"end":i,"count":1})
groups = []
for r in runs:
    if groups and r["start"] - groups[-1]["end"] <= 128:
        groups[-1]["end"] = r["end"]
        groups[-1]["different_bytes"] += r["count"]
        groups[-1]["contiguous_runs"] += 1
    else:
        groups.append({"start":r["start"],"end":r["end"],"different_bytes":r["count"],"contiguous_runs":1})
def visible(buf):
    return "".join(chr(x) if 32 <= x <= 126 else "." for x in buf)
symbol_status={"available":False}
if args.system_map and args.system_map.is_file():
    syms=[]
    for line in args.system_map.read_text(errors="replace").splitlines():
        x=line.split(maxsplit=2)
        if len(x)!=3: continue
        try: addr=int(x[0],16)
        except ValueError: continue
        syms.append((addr,x[1],x[2]))
    syms.sort()
    base=next((x[0] for x in syms if x[2]=="_text"),None)
    if base is not None:
        symbol_status={"available":True,"assumed_image_base":hex(base),
                       "limitation":"Raw Image offsets mapped assuming _text at byte zero; requires ELF validation"}
        addresses=[x[0] for x in syms]
        for g in groups:
            pos=bisect.bisect_right(addresses,base+g["start"])-1
            if pos >= 0:
                near=syms[pos]
                g["nearest_symbol"]={"name":near[2],"offset":base+g["start"]-near[0],"type":near[1]}
for g in groups:
    start=max(0,g["start"]-40)
    end=min(len(a),g["start"]+104)
    g["built_excerpt"]={"hex":a[start:end].hex(" "),"ascii":visible(a[start:end])}
    g["google_excerpt"]={"hex":b[start:end].hex(" "),"ascii":visible(b[start:end])}
    g["offset_excerpt_start"]=start
    g["span"]=g["end"]-g["start"]+1
markers={}
for m in (b"IKCFG_ST",b"IKCFG_ED",b"Linux version ",b"-----BEGIN CERTIFICATE-----",b"Android Kernel"):
    markers[m.decode()]={
        "built":[x.start() for x in list(re.finditer(re.escape(m),a))[:4]],
        "google":[x.start() for x in list(re.finditer(re.escape(m),b))[:4]]}
ik_start,ik_end=a.find(b"IKCFG_ST"),a.find(b"IKCFG_ED")
ik_start_g,ik_end_g=b.find(b"IKCFG_ST"),b.find(b"IKCFG_ED")
ik={"present":min(ik_start,ik_end,ik_start_g,ik_end_g)>=0}
if ik["present"]:
    ik.update(built_range=[ik_start,ik_end+8],google_range=[ik_start_g,ik_end_g+8],
              equal=a[ik_start:ik_end+8]==b[ik_start_g:ik_end_g+8],
              changed_bytes_in_area=sum(ik_start<=z<ik_end+8 for z in positions))
result={
    "status":"NOT_FLASH_QUALIFIED",
    "built_sha256":hashlib.sha256(a).hexdigest(),
    "google_sha256":hashlib.sha256(b).hexdigest(),
    "bytes":len(a),"identical":a==b,"difference_bytes":len(positions),
    "contiguous_difference_runs":len(runs),
    "groups_with_gap_le_128":len(groups),
    "all_group_summaries":[{k:v for k,v in g.items() if k not in ("built_excerpt","google_excerpt")} for g in groups],
    "groups_detailed":groups[:100],
    "markers":markers,"embedded_config":ik,"system_map":symbol_status,
    "limitations":["Do not infer flashed OEM module compatibility from GKI symbol equivalence",
                   "Do not patch an Image to artificially match Google CI",
                   "A build-local autogenerated signing certificate can cause binary differences; inspect evidence before attributing cause"]
}
args.output.parent.mkdir(parents=True,exist_ok=True)
args.output.write_text(json.dumps(result,indent=2)+"\n")
txt=args.output.with_suffix(".txt")
with txt.open("w") as f:
    for key in ("built_sha256","google_sha256","bytes","identical","difference_bytes","contiguous_difference_runs","groups_with_gap_le_128"):
        f.write(f"{key}: {result[key]}\n")
    f.write(f"map: {symbol_status}\nconfig: {ik}\n")
    for g in groups[:100]:
        f.write(f"offset={g['start']}..{g['end']} changed={g['different_bytes']} nearest={g.get('nearest_symbol')}\n")
        f.write(f"  BUILT : {g['built_excerpt']['ascii']}\n")
        f.write(f"  GOOGLE: {g['google_excerpt']['ascii']}\n")
        f.write(f"  BUILT_HEX : {g['built_excerpt']['hex']}\n")
        f.write(f"  GOOGLE_HEX: {g['google_excerpt']['hex']}\n")
print("DIFF_BYTES:", len(positions))
print("GROUPS:", len(groups))
print("GROUPS_TOP:", json.dumps(sorted(result["all_group_summaries"], key=lambda g:-g["different_bytes"])[:20]))
print("MAP:",symbol_status)
print("CONFIG_MARKERS:",ik)
